/** Lấy danh sách quy tắc GET /api/rule */
export async function rule(
  params: {
    // query
    /** Trang hiện tại */
    current?: number;
    /** Kích thước trang */
    pageSize?: number;
  },
  options?: { [key: string]: any },
) {
  return request<API.RuleList>('/api/rule', {
    method: 'GET',
    params: {
      ...params,
    },
    ...(options || {}),
  });
}

/** Cập nhật quy tắc PUT /api/rule */
